// Human movement pose sent from the GUI while actively steering a headless character (Option 3: headless remains
// authoritative and applies this pose to its own movement body + live GameConnection).
struct DriveMove {
    glm::vec3 position{0.0f}; // world spawn position (feet + floor_offset)
    float heading = 0.0f;     // EQ heading (0..512)
    glm::vec3 velocity{0.0f};
    float speed_run = 0.0f;
    bool moving = false;
    std::uint8_t stand_state = 100;
    std::uint32_t standing_on = 0;
    bool active = false; // true while manual keys/mouse are driving; false hands control back immediately
};

// Whether an outgoing packet generated by a GUI control mirror may be forwarded verbatim to the headless's live
// session. Packets that own session lifecycle, position tracking, or client-authoritative inventory/combat state are
// excluded here and handled semantically on the headless instead.
bool drive_forward_allowed(const AppPacket& packet, bool world);

